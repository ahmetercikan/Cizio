/** Simgenin tam SVG'si (ekranda ve resim olarak). */
export function iconSvg(name: string, size = 48) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 48 48">${ICONS[name] ?? ICONS.yildiz}</svg>`;
}

/** 3B baloncuk vb. için tuvale çizilmiş simge (resim yüklenince `done` çağrılır). */
export function drawIcon(ctx: CanvasRenderingContext2D, name: string, x: number, y: number, size: number, done: () => void) {
  const img = new Image();
  img.onload = () => {
    ctx.drawImage(img, x, y, size, size);
    done();
  };
  img.src = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(iconSvg(name, size))}`;
}
